          AND [InitialCodeCommit] = @SuccessorCodeCommit
          AND [DecisionRef] = @SuccessorDecisionRef
          AND [IsActive] = 1
    )
    OR NOT EXISTS
    (
        SELECT 1
        FROM dbo.StrategyVersion
        WHERE [VersionId] = @PredecessorId
          AND [VersionName] = @PredecessorName
          AND [IsActive] = 0
    )
    THROW 51091, 'The exact v3.2 successor is not solely active or v3.1 is not inactive.', 1;

IF EXISTS
(
    SELECT [MinCompositeScore],[MinDirectionProb],[RegressionVeto],[StopLossPercent],
           [WarningPercent],[MaxPositions],[MinBreakoutProb],[MinDirectionEdge],
           [MaxDownProb],[BreadthVetoThreshold],[StrongBreakoutOverride],[StrongEdgeOverride]
    FROM dbo.StrategyVersion WHERE [VersionId] = @SuccessorId
    EXCEPT
    SELECT [MinCompositeScore],[MinDirectionProb],[RegressionVeto],[StopLossPercent],
           [WarningPercent],[MaxPositions],[MinBreakoutProb],[MinDirectionEdge],
           [MaxDownProb],[BreadthVetoThreshold],[StrongBreakoutOverride],[StrongEdgeOverride]
    FROM dbo.StrategyVersion WHERE [VersionId] = @PredecessorId
)
OR EXISTS
(
    SELECT [MinCompositeScore],[MinDirectionProb],[RegressionVeto],[StopLossPercent],
           [WarningPercent],[MaxPositions],[MinBreakoutProb],[MinDirectionEdge],
           [MaxDownProb],[BreadthVetoThreshold],[StrongBreakoutOverride],[StrongEdgeOverride]
    FROM dbo.StrategyVersion WHERE [VersionId] = @PredecessorId
    EXCEPT
    SELECT [MinCompositeScore],[MinDirectionProb],[RegressionVeto],[StopLossPercent],
           [WarningPercent],[MaxPositions],[MinBreakoutProb],[MinDirectionEdge],
           [MaxDownProb],[BreadthVetoThreshold],[StrongBreakoutOverride],[StrongEdgeOverride]
    FROM dbo.StrategyVersion WHERE [VersionId] = @SuccessorId
)
    THROW 51092, 'The v3.2 thresholds differ from the v3.1 predecessor.', 1;

IF EXISTS
(
    SELECT [ModelId],[CompositeWeight],[IsRequired],[Role]
    FROM dbo.StrategyVersionModel WHERE [VersionId] = @SuccessorId
    EXCEPT
    SELECT [ModelId],[CompositeWeight],[IsRequired],[Role]
    FROM dbo.StrategyVersionModel WHERE [VersionId] = @PredecessorId
)
OR EXISTS
(
    SELECT [ModelId],[CompositeWeight],[IsRequired],[Role]
    FROM dbo.StrategyVersionModel WHERE [VersionId] = @PredecessorId
    EXCEPT
    SELECT [ModelId],[CompositeWeight],[IsRequired],[Role]
    FROM dbo.StrategyVersionModel WHERE [VersionId] = @SuccessorId
)
    THROW 51093, 'The v3.2 model associations differ from the v3.1 predecessor.', 1;

-- Verify every affected count and exact historical run/outcome reference.
IF (SELECT COUNT_BIG(*) FROM dbo.LeadershipData) <> @LeadershipRowsBefore
    OR (SELECT COUNT_BIG(*) FROM dbo.StrategyVersion) <>
        @StrategyVersionRowsBefore + CASE WHEN @IsFirstApplication = 1 THEN 1 ELSE 0 END
    OR (SELECT COUNT_BIG(*) FROM dbo.StrategyVersionModel) <>
        @StrategyVersionModelRowsBefore + CASE WHEN @IsFirstApplication = 1 THEN @PredecessorModelCount ELSE 0 END
    OR (SELECT COUNT_BIG(*) FROM dbo.CalibrationRun) <> @CalibrationRunRowsBefore
    OR (SELECT COUNT_BIG(*) FROM dbo.CalibrationCandidate) <> @CalibrationCandidateRowsBefore
    OR (SELECT COUNT_BIG(*) FROM dbo.CalibrationLensEvaluation) <> @CalibrationLensRowsBefore
    OR (SELECT COUNT_BIG(*) FROM dbo.CalibrationOutcomeDefinition) <> @CalibrationDefinitionRowsBefore
    OR (SELECT COUNT_BIG(*) FROM dbo.CalibrationCandidateOutcome) <> @CalibrationOutcomeRowsBefore
    THROW 51094, 'A protected leadership, strategy, or calibration row count changed unexpectedly.', 1;

IF EXISTS
(
    SELECT [RunId], [StrategyVersionId] FROM @CalibrationRunReferences
    EXCEPT
    SELECT [RunId], [StrategyVersionId] FROM dbo.CalibrationRun
)
