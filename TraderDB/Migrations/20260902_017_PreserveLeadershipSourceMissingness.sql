         + CASE WHEN [ActiveDecliners] IS NULL THEN 1 ELSE 0 END
         + CASE WHEN [ActiveN] IS NULL THEN 1 ELSE 0 END) IN (1, 2)
       OR
        (
            [ActiveAdvancers] IS NOT NULL
            AND [ActiveDecliners] IS NOT NULL
            AND [ActiveN] IS NOT NULL
            AND NOT ([ActiveAdvancers] = 0 AND [ActiveDecliners] = 0 AND [ActiveN] = 0)
            AND
            (
                [ActiveAdvancers] < 0
                OR [ActiveDecliners] < 0
                OR [ActiveN] <= 0
