-- Ask this SQL Server engine to serialize the intended expressions. Comparing
-- its own definitions avoids hand-maintained canonical text while retaining every
-- parenthesis, operator, comma, and operand boundary during later normalization.
CREATE TABLE #ExpectedLegacyStrategyIdentityConstraint
(
    [InitialCodeCommit] NVARCHAR(128) NULL,
    [DecisionRef] NVARCHAR(64) NULL,
    CHECK
    (
        ([InitialCodeCommit] IS NULL AND [DecisionRef] IS NULL)
        OR
        (
            LEN(LTRIM(RTRIM([InitialCodeCommit]))) BETWEEN 7 AND 128
            AND LEN(LTRIM(RTRIM([DecisionRef]))) BETWEEN 1 AND 64
        )
    )
);

CREATE TABLE #ExpectedFinalStrategyIdentityConstraint
(
    [InitialCodeCommit] NVARCHAR(128) NULL,
    [DecisionRef] NVARCHAR(64) NULL,
    CHECK
    (
        ([InitialCodeCommit] IS NULL AND [DecisionRef] IS NULL)
        OR
        (
            [InitialCodeCommit] IS NOT NULL
            AND [DecisionRef] IS NOT NULL
            AND LEN(LTRIM(RTRIM([InitialCodeCommit]))) BETWEEN 7 AND 128
            AND LEN(LTRIM(RTRIM([DecisionRef]))) BETWEEN 1 AND 64
        )
    )
);

CREATE TABLE #ExpectedLeadershipConstraint
(
    [ActiveAdvancers] INT NULL,
    [ActiveDecliners] INT NULL,
    [ActiveN] INT NULL,
    CHECK
    (
        (
            [ActiveAdvancers] IS NULL
            AND [ActiveDecliners] IS NULL
            AND [ActiveN] IS NULL
        )
        OR
        (
            [ActiveAdvancers] IS NOT NULL
            AND [ActiveDecliners] IS NOT NULL
            AND [ActiveN] IS NOT NULL
            AND [ActiveAdvancers] >= 0
            AND [ActiveDecliners] >= 0
            AND [ActiveN] > 0
            AND CONVERT(BIGINT, [ActiveAdvancers]) + [ActiveDecliners] <= [ActiveN]
        )
    )
);

