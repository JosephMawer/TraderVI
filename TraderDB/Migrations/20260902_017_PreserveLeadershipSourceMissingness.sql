/*
    Preserve leadership-source missingness and activate its strategy identity under ADR-0043.

    Expected preconditions:
      - dbo.LeadershipData, dbo.StrategyVersion, dbo.StrategyVersionModel, and the
        calibration evidence-ledger tables exist.
      - The complete strategy code-identity columns exist. First application has the
        exact enabled/trusted legacy ADR-0042 check; rerun has the exact enabled/trusted
        strengthened check installed by this migration.
      - On first application, all three Active* columns are INT NOT NULL, the new
        leadership constraint is absent, and the sole active strategy is the exact
        v3.1-rs-date-aligned predecessor.
      - On an idempotent rerun, all three Active* columns are INT NULL, the exact
        leadership constraint is enabled and trusted, and the exact v3.2 successor
        is already the sole active strategy.

    Data effects:
      - Makes ActiveAdvancers, ActiveDecliners, and ActiveN nullable as one observation.
      - Converts only the legacy 0/0/0 sentinel triple to NULL/NULL/NULL.
      - Adds a trusted check requiring either complete missingness or one complete,
        non-negative observation whose BIGINT advancer/decliner sum does not exceed N.
      - Replaces the legacy ADR-0042 code-identity check with a trusted strengthened
        form that explicitly requires both identity values before checking their lengths.
      - Clones every threshold and model association from the fixed v3.1 predecessor
        into the fixed v3.2-leadership-missingness identity, then activates v3.2.
      - Does not update, relabel, invalidate, or delete any historical CalibrationRun,
        candidate, lens, outcome-definition, or candidate-outcome row or reference.

    Recovery:
      - Schema, sentinel normalization, strategy cloning, and activation are one
        SERIALIZABLE transaction with XACT_ABORT. Any failed guard rolls back the unit.
      - After a committed result, use the required fresh verified backup or a separately
        authorized corrective migration; do not edit this file after application.

    Review and execute manually only after a fresh verified backup and explicit
    authorization. Do not deploy a DACPAC.
*/

